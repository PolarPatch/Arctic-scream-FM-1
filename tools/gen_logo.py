"""Arctic Scream p0larpatch's boot logo: the PolarPatch logo (assets/polarpatch-logo.png, Copyright (C) PolarPatch, not under the
GPL: see LICENSING.md) at LOGO_W x LOGO_H, 16 greys, two pixels a byte (the high nibble the left one)
-> firmware/gen/polarpatch_logo.h. The boot screen tints the greys from the background to ice.

  python3 tools/gen_logo.py          (needs Pillow)
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "polarpatch-logo.png"
OUT = ROOT / "firmware" / "gen" / "polarpatch_logo.h"
SIZE = 160


def main():
    im = Image.open(SRC).convert("L").resize((SIZE, SIZE), Image.LANCZOS)
    px = [min(15, (v * 16) // 256) for v in im.tobytes()]
    data = [px[i] << 4 | px[i + 1] for i in range(0, len(px), 2)]
    out = ["/* generated by tools/gen_logo.py: the PolarPatch logo (Copyright (C) PolarPatch, not under the GPL), "
           f"{SIZE} x {SIZE},",
           " * 16 greys, two pixels a byte (the high nibble the left one) */",
           f"#define LOGO_W {SIZE}",
           f"#define LOGO_H {SIZE}",
           "static const uint8_t LOGO[LOGO_W * LOGO_H / 2] = {"]
    for i in range(0, len(data), 20):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
    out.append("};")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(data)} B")


if __name__ == "__main__":
    main()
